    static func wordmarkPath(_ c: CGPoint, _ R: Double, dx: Double = 0) -> Path {
        let o = wordmarkOps
        func pt(_ j: Int) -> CGPoint { CGPoint(x: Double(c.x) + dx + o[j] * R, y: Double(c.y) + o[j + 1] * R) }
        var p = Path()
        var i = 0
        while i < o.count {
            switch o[i] {
            case 0: p.move(to: pt(i + 1)); i += 3
            case 1: p.addLine(to: pt(i + 1)); i += 3
            case 2: p.addCurve(to: pt(i + 5), control1: pt(i + 1), control2: pt(i + 3)); i += 7
            default: p.closeSubpath(); i += 1
            }
        }
        return p
    }


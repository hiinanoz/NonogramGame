    // MARK: Easing
    static func clamp(_ x: Double) -> Double { max(0, min(1, x)) }
    static func seg(_ t: Double, _ a: Double, _ b: Double) -> Double { clamp((t - a) / (b - a)) }
    static func lerp(_ a: Double, _ b: Double, _ p: Double) -> Double { a + (b - a) * p }
    static func easeOut(_ x: Double) -> Double { 1 - pow(1 - x, 3) }
    static func easeInOut(_ x: Double) -> Double { x < 0.5 ? 4 * x * x * x : 1 - pow(-2 * x + 2, 3) / 2 }
    static func easeOutBack(_ x: Double) -> Double {
        let c1 = 1.70158, c3 = c1 + 1
        return 1 + c3 * pow(x - 1, 3) + c1 * pow(x - 1, 2)
    }

    static func circle(_ c: CGPoint, _ r: Double) -> Path {
        let r = max(0, r)
        return Path(ellipseIn: CGRect(x: Double(c.x) - r, y: Double(c.y) - r, width: 2 * r, height: 2 * r))
    }

    // MARK: Frame
    static func draw(_ ctx: inout GraphicsContext, size: CGSize, t: Double) {
        let W = Double(size.width), H = Double(size.height)
        let cx = W / 2, cy = H / 2
        let R0 = min(W, H) * 0.20          // ortadaki logo yarıçapı

        // Son kilit (logo + yazı) ölçüleri — logodaki oranların aynısı
        let leftExt = 1.1                                    // renkli dairelerin sol taşması (R)
        let total = leftExt + wordmarkMaxX                   // toplam genişlik (R)
        let logoW = R0 * (leftExt + 1.07)                    // ilk O logosunun genişliği (renkli daireler dahil)
        let rf = logoW / total                               // yazılı hal bu genişliği geçmez
        let finalX = cx - total * rf / 2 + leftExt * rf

        // Logo konum / ölçek
        let m = easeInOut(seg(t, 1.95, 2.45))                       // sola kayma
        let pop = 1 + 0.06 * sin(.pi * seg(t, 1.15, 1.7))           // dolarken hafif zıplama
        let R = lerp(R0, rf, m) * pop
        let c = CGPoint(x: lerp(cx, finalX, m), y: cy)

        // 1) THiNKS yazısı soldan sağa açılır (kare 08–10). Önce çizilir ki logo yazının ucunu örtsün (orijinaldeki gibi).
        let rv = easeOut(seg(t, 2.15, 2.75))
        if rv > 0 {
            let textLeft = Double(c.x) + wordmarkMinX * R
            let textW = (wordmarkMaxX - wordmarkMinX) * R
            let fade = textW * 0.35
            let rx = textLeft - fade + (textW + fade) * rv
            let x0 = textLeft - R, x1 = rx + fade
            let loc = clamp((rx - x0) / (x1 - x0))
            ctx.drawLayer { l in
                l.fill(wordmarkPath(c, R, dx: 0.2 * R * (1 - rv)), with: .color(.white))
                l.blendMode = .destinationIn
                l.fill(Path(CGRect(x: 0, y: 0, width: W, height: H)),
                       with: .linearGradient(Gradient(stops: [
                            .init(color: .black, location: 0),
                            .init(color: .black, location: loc),
                            .init(color: .clear, location: 1),
                       ]), startPoint: CGPoint(x: x0, y: 0), endPoint: CGPoint(x: x1, y: 0)))
            }
        }

        // 2) Partiküller (dönüş + patlama)
        let pB = seg(t, 0.3, 1.15)
        let orbitA = seg(t, 0.35, 0.55) * (1 - seg(t, 1.0, 1.2))
        let burst = seg(t, 1.4, 1.95)
        let burstA = sin(.pi * burst)
        for p in particles {
            let states: [(Double, Double, Double)] = [
                (orbitA, p.d * (0.9 + 0.1 * pB), p.a + 50 * pB),
                (burstA, p.d * (0.95 + 0.45 * easeOut(burst)), p.a + 20),
            ]
            for (alpha, dist, ang) in states where alpha > 0.001 {
                let a = ang * .pi / 180
                let pos = CGPoint(x: Double(c.x) + R * dist * cos(a), y: Double(c.y) + R * dist * sin(a))
                let r = R * p.s
                var l = ctx
                l.opacity = alpha
                if p.ring { l.stroke(circle(pos, r), with: .color(p.col), lineWidth: r * 0.45) }
                else { l.fill(circle(pos, r), with: .color(p.col)) }
            }
        }

        // 3) Başlangıç noktası (kare 01)
        let dotIn = easeOutBack(seg(t, 0.0, 0.3))
        let dotOut = seg(t, 0.35, 0.55)
        if dotOut < 1 && dotIn > 0 {
            let r = R0 * 0.085 * dotIn * (1 - 0.6 * dotOut)
            var l = ctx
            l.opacity = 1 - dotOut
            l.fill(circle(c, r), with: .linearGradient(Gradient(colors: [magenta, blue]),
                                                      startPoint: CGPoint(x: Double(c.x) - r, y: Double(c.y) + r),
                                                      endPoint: CGPoint(x: Double(c.x) + r, y: Double(c.y) - r)))
        }

        // 4) Üç renkli dolu daire: merkezden dönerek büyür ve kaymış konumlarına oturur
        for (col, v, delay) in discs {
            let p = seg(t, 0.3 + delay, 1.1 + delay)
            guard p > 0 else { continue }
            let q = easeOut(p)
            let finalDist = Double(hypot(v.dx, v.dy))
            let finalAng = Double(atan2(v.dy, v.dx))
            let ang = finalAng - (1 - q) * 200 * .pi / 180
            let dist = lerp(0.55, finalDist, q) * R
            let dc = CGPoint(x: Double(c.x) + dist * cos(ang), y: Double(c.y) + dist * sin(ang))
            var l = ctx
            l.opacity = seg(t, 0.3 + delay, 0.45 + delay)
            l.fill(circle(dc, R * lerp(0.08, 1, easeOutBack(p))), with: .color(col))
        }

        // 5) Beyaz disk + siyah delik (kare 05)
        ctx.fill(circle(c, R * easeOut(seg(t, 1.1, 1.45))), with: .color(.white))
        ctx.fill(circle(c, R * 0.24 * easeOutBack(seg(t, 1.3, 1.6))), with: .color(.black))

    }
